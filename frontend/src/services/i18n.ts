export function formatLocalizedNumber(num: number | string, lang: string = 'en'): string {
  const str = String(num);
  const digits = INDIC_DIGITS[lang] || INDIC_DIGITS.en;
  if (!digits || lang === 'en' || lang === 'es' || lang === 'sw' || lang === 'fr' || lang === 'id' || lang === 'pt') return str;
  return str.replace(/\d/g, (d) => digits[parseInt(d, 10)]);
}

export function formatLocalizedCurrency(amount: number, lang: string = 'en', currencyCode?: string): string {
  const cur = getCurrencyConfig(currencyCode || getStoredCurrency());
  try {
    const formatted = Math.round(amount).toLocaleString(cur.locale);
    return `${cur.symbol}${formatLocalizedNumber(formatted, lang)}`;
  } catch (_) {
    return `${cur.symbol}${formatLocalizedNumber(Math.round(amount), lang)}`;
  }
}

